//! The decision log, docs/adr/.
//!
//! `cargo poly adr lint` checks every file that looks like an ADR (NNNN-*.md) for:
//!   - a filename of the form NNNN-kebab-title.md
//!   - YAML front matter between --- fences
//!   - the required fields, with valid values
//!   - no duplicate ADR numbers (numbers are never reused)
//!
//! It warns, without failing, when a brick or project named in `affects` does not
//! exist. An ADR is immutable and may outlive the bricks it names, so that is a
//! heads-up, not an error (ADR-0006).
//!
//! `cargo poly adr index` regenerates docs/adr/index/: one Markdown file per brick
//! listing the ADRs whose `affects` names it, plus index/README.md with the full list.
//! The files there are generated output; do not edit them by hand.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use regex_lite::Regex;
use serde_yaml_ng::{Mapping, Value};

use crate::util;

const DIR: &str = "docs/adr";
const INDEX_DIR: &str = "docs/adr/index";
const TEMPLATE: &str = "0000-adr-template.md";
const REQUIRED: [&str; 5] = [
    "status",
    "date",
    "decision-makers",
    "affects",
    "interface-impact",
];
const VALID_IMPACT: [&str; 3] = ["none", "new", "breaking"];
const STATUS_PREFIXES: [&str; 4] = ["proposed", "accepted", "deprecated", "superseded by adr-"];
const KINDS: [&str; 3] = ["components", "bases", "projects"];
const GENERATED_NOTE: &str = "_Generated by `cargo poly adr index`. Do not edit by hand._";

fn filename_re() -> Regex {
    Regex::new(r"^(\d{4})-[a-z0-9]+(?:-[a-z0-9]+)*\.md$").expect("valid regex")
}

/// Is this repo-relative path a numbered decision record (not the template or README)?
pub fn is_record_path(path: &str) -> bool {
    Regex::new(r"^docs/adr/\d{4}-.+\.md$")
        .expect("valid regex")
        .is_match(path)
}

/// The numbered records in docs/adr/, sorted. The template and README are skipped.
fn records() -> Vec<PathBuf> {
    let mut out: Vec<PathBuf> = util::walk(Path::new(DIR))
        .into_iter()
        .filter(|p| p.parent() == Some(Path::new(DIR)))
        .filter(|p| p.extension().is_some_and(|e| e == "md"))
        .filter(|p| {
            let name = p
                .file_name()
                .unwrap_or_default()
                .to_string_lossy()
                .to_lowercase();
            name != TEMPLATE && name != "readme.md"
        })
        .collect();
    out.sort();
    out
}

/// The YAML front matter between the opening and closing `---` fences.
pub fn front_matter(text: &str) -> Result<Mapping, String> {
    let Some(rest) = text.strip_prefix("---") else {
        return Err("no YAML front matter (the file must start with ---)".to_string());
    };
    let Some(end) = rest.find("\n---") else {
        return Err("front matter is not closed with a second ---".to_string());
    };
    let value: Value = serde_yaml_ng::from_str(&rest[..end])
        .map_err(|e| format!("front matter is not valid YAML: {e}"))?;
    match value {
        Value::Mapping(m) => Ok(m),
        Value::Null => Ok(Mapping::new()),
        _ => Err("front matter did not parse to a set of fields".to_string()),
    }
}

/// The names under `affects.<key>` as strings (missing or malformed: empty).
pub fn names(front: &Mapping, key: &str) -> Vec<String> {
    front
        .get("affects")
        .and_then(Value::as_mapping)
        .and_then(|a| a.get(key))
        .and_then(Value::as_sequence)
        .map(|seq| seq.iter().map(scalar).collect())
        .unwrap_or_default()
}

/// A YAML scalar as text, the way a reader would write it.
pub fn scalar(value: &Value) -> String {
    match value {
        Value::String(s) => s.clone(),
        Value::Number(n) => n.to_string(),
        Value::Bool(b) => b.to_string(),
        Value::Null => String::new(),
        other => format!("{other:?}"),
    }
}

fn is_blank(value: Option<&Value>) -> bool {
    match value {
        None | Some(Value::Null) => true,
        Some(Value::String(s)) => s.is_empty(),
        _ => false,
    }
}

fn title(text: &str) -> Option<String> {
    text.lines()
        .find_map(|l| l.strip_prefix("# "))
        .map(|t| t.trim().to_string())
}

/// The bricks and projects that exist, by kind. `None` when that directory is absent.
fn known() -> BTreeMap<&'static str, Option<Vec<String>>> {
    KINDS
        .iter()
        .map(|kind| {
            let dirs = util::subdirs(Path::new(kind))
                .map(|names| names.into_iter().filter(|n| !n.starts_with('.')).collect());
            (*kind, dirs)
        })
        .collect()
}

pub fn lint() -> Result<u8, String> {
    if !Path::new(DIR).is_dir() {
        println!("No {DIR}/ directory found, nothing to lint.");
        return Ok(0);
    }
    let filename_re = filename_re();
    let known = known();
    let mut errors: Vec<String> = Vec::new();
    let mut warnings: Vec<String> = Vec::new();
    let mut seen: BTreeMap<String, String> = BTreeMap::new();

    for path in records() {
        let name = path
            .file_name()
            .unwrap_or_default()
            .to_string_lossy()
            .into_owned();
        let Some(caps) = filename_re.captures(&name) else {
            errors.push(format!(
                "{name}: filename must look like NNNN-kebab-title.md"
            ));
            continue;
        };
        let number = caps[1].to_string();
        if let Some(other) = seen.get(&number) {
            errors.push(format!(
                "{name}: ADR number {number} is already used by {other}; numbers are never reused"
            ));
        } else {
            seen.insert(number, name.clone());
        }

        let text = util::read(&path)?;
        let front = match front_matter(&text) {
            Ok(f) => f,
            Err(e) => {
                errors.push(format!("{name}: {e}"));
                continue;
            }
        };

        for field in REQUIRED {
            if is_blank(front.get(field)) {
                errors.push(format!("{name}: missing required field `{field}`"));
            }
        }

        let status = front
            .get("status")
            .map(scalar)
            .unwrap_or_default()
            .trim()
            .to_lowercase();
        if !status.is_empty() && !STATUS_PREFIXES.iter().any(|p| status.starts_with(p)) {
            errors.push(format!(
                "{name}: status '{}' is not one of proposed / accepted / deprecated / superseded by ADR-NNNN",
                front.get("status").map(scalar).unwrap_or_default()
            ));
        }

        if let Some(impact) = front.get("interface-impact") {
            let value = scalar(impact).trim().to_lowercase();
            if !VALID_IMPACT.contains(&value.as_str()) {
                errors.push(format!(
                    "{name}: interface-impact '{}' must be one of none / new / breaking",
                    scalar(impact)
                ));
            }
        }

        if let Some(affects) = front.get("affects") {
            check_affects(&name, affects, &known, &mut errors, &mut warnings);
        }
    }

    if !warnings.is_empty() {
        println!("ADR lint warnings (not blocking):\n");
        for w in &warnings {
            println!("  - {w}");
        }
        println!(
            "\nA record is immutable and may outlive the bricks it names, so this is only a heads-up. \
             Check the spelling if the brick still exists.\n"
        );
    }
    if !errors.is_empty() {
        println!("ADR lint found problems:\n");
        for e in &errors {
            println!("  - {e}");
        }
        println!(
            "\nFix the files above. Each ADR must follow {DIR}/{TEMPLATE}. If you are unsure what a field \
             means, see CONTRIBUTING.md."
        );
        return Ok(1);
    }
    println!("ADR lint passed: {} record(s) look good.", seen.len());
    Ok(0)
}

fn check_affects(
    name: &str,
    affects: &Value,
    known: &BTreeMap<&str, Option<Vec<String>>>,
    errors: &mut Vec<String>,
    warnings: &mut Vec<String>,
) {
    let Some(map) = affects.as_mapping() else {
        errors.push(format!(
            "{name}: `affects` must have components/bases/projects lists"
        ));
        return;
    };
    for kind in KINDS {
        let Some(values) = map.get(kind) else {
            errors.push(format!("{name}: `affects` is missing `{kind}`"));
            continue;
        };
        let values: Vec<String> = match values {
            Value::Null => Vec::new(),
            Value::Sequence(seq) => seq.iter().map(scalar).collect(),
            _ => {
                errors.push(format!("{name}: `affects.{kind}` must be a list"));
                continue;
            }
        };
        let Some(Some(existing)) = known.get(kind) else {
            continue;
        };
        for value in values {
            if value != "*" && !existing.contains(&value) {
                warnings.push(format!(
                    "{name}: `affects.{kind}` names '{value}', but no such {} exists now",
                    &kind[..kind.len() - 1]
                ));
            }
        }
    }
}

struct Entry {
    file: String,
    title: String,
    status: String,
}

fn line(entry: &Entry, rel: &str) -> String {
    let suffix = if entry.status.is_empty() {
        String::new()
    } else {
        format!(" ({})", entry.status)
    };
    format!("- [{}]({}{}){}", entry.title, rel, entry.file, suffix)
}

pub fn index() -> Result<u8, String> {
    if !Path::new(DIR).is_dir() {
        println!("No {DIR}/ directory, nothing to index.");
        return Ok(0);
    }
    let mut all: Vec<Entry> = Vec::new();
    let mut by_brick: BTreeMap<(String, String), Vec<usize>> = BTreeMap::new();

    for path in records() {
        let text = util::read(&path)?;
        let front = front_matter(&text).unwrap_or_default();
        let file = path
            .file_name()
            .unwrap_or_default()
            .to_string_lossy()
            .into_owned();
        let title = title(&text).unwrap_or_else(|| {
            path.file_stem()
                .unwrap_or_default()
                .to_string_lossy()
                .into_owned()
        });
        let status = front
            .get("status")
            .map(scalar)
            .unwrap_or_default()
            .trim()
            .to_string();
        let i = all.len();
        all.push(Entry {
            file,
            title,
            status,
        });
        for kind in KINDS {
            for brick in names(&front, kind) {
                by_brick
                    .entry((kind.to_string(), brick))
                    .or_default()
                    .push(i);
            }
        }
    }

    let index_dir = Path::new(INDEX_DIR);
    fs::create_dir_all(index_dir).map_err(|e| format!("cannot create {INDEX_DIR}: {e}"))?;
    for old in util::walk(index_dir) {
        if old.extension().is_some_and(|e| e == "md") {
            fs::remove_file(&old).map_err(|e| format!("cannot remove {}: {e}", old.display()))?;
        }
    }

    for ((kind, brick), entries) in &by_brick {
        let safe = if brick == "*" {
            "_all_"
        } else {
            brick.as_str()
        };
        let mut body = vec![format!(
            "# ADRs affecting {}: {brick}",
            &kind[..kind.len() - 1]
        )];
        body.extend(entries.iter().map(|&i| line(&all[i], "../")));
        body.push(String::new());
        body.push(GENERATED_NOTE.to_string());
        let target = index_dir.join(format!("{kind}-{safe}.md"));
        fs::write(&target, body.join("\n") + "\n")
            .map_err(|e| format!("cannot write {}: {e}", target.display()))?;
    }

    let mut readme = vec![
        "# ADR index".to_string(),
        "Generated view of the decision log. Do not edit by hand; run `cargo poly adr index`."
            .to_string(),
        String::new(),
        "## All ADRs".to_string(),
    ];
    readme.extend(all.iter().map(|e| line(e, "../")));
    readme.push(String::new());
    readme.push("## By brick".to_string());
    for ((kind, brick), entries) in &by_brick {
        let safe = if brick == "*" {
            "_all_"
        } else {
            brick.as_str()
        };
        readme.push(format!(
            "- {} `{brick}`: [{kind}-{safe}.md]({kind}-{safe}.md) ({})",
            &kind[..kind.len() - 1],
            entries.len()
        ));
    }
    readme.push(String::new());
    let target = index_dir.join("README.md");
    fs::write(&target, readme.join("\n"))
        .map_err(|e| format!("cannot write {}: {e}", target.display()))?;

    println!(
        "Wrote index for {} ADR(s) across {} brick view(s).",
        all.len(),
        by_brick.len()
    );
    Ok(0)
}
